from sqlmodel import Session, select
from models.FileRecord import QuestionAnswer
from pathlib import Path

def delete_qna_by_file(session: Session, file_id: int) -> int:
    """
    Delete all QuestionAnswer entries for a given file_id.

    Args:
        session (Session): SQLModel database session
        file_id (int): ID of the file whose QA pairs should be deleted

    Returns:
        int: Number of QA pairs deleted
    """
    # Fetch all QA records for this file_id
    qas_to_delete = session.exec(
        select(QuestionAnswer).where(QuestionAnswer.file_id == file_id)
    ).all()

    if not qas_to_delete:
        print(f"[INFO] No QA pairs found for file_id {file_id}.")
        return 0
    
    

    deleted_count = len(qas_to_delete)
    for qa in qas_to_delete:
        session.delete(qa)

    session.commit()
    print(f"[INFO] Deleted {deleted_count} QA pairs for file_id {file_id}.")
    return deleted_count

def delete_qna_by_question_id(session: Session, question_id: int) -> bool:
    """
    Delete a single QuestionAnswer entry by question_id.

    Args:
        session (Session): SQLModel database session.
        question_id (int): ID of the question to delete.

    Returns:
        bool: True if deleted, False if no record found.
    """
    qa_to_delete = session.get(QuestionAnswer, question_id)
    if not qa_to_delete:
        return False

    session.delete(qa_to_delete)
    session.commit()
    return True

def delete_generated_files(file_path: str):
    """
    Deletes files generated by the process_file pipeline:
    parsed, generated, and curated files.
    """
    def filename(path: str) -> str:
        # extract the filename without extension
        return Path(path).stem

    parsed_file = Path(f"data/parsed/{filename(file_path)}.lance")
    generated_file = Path(f"data/generated/{filename(file_path)}_qa_pairs.json")
    curated_file = Path(f"data/curated/{filename(file_path)}_qa_pairs_cleaned.json")
    

    for f in [parsed_file, generated_file, curated_file]:
        try:
            if f.exists():
                f.unlink()
                print(f"[INFO] Deleted: {f}")
        except Exception as e:
            print(f"[ERROR] Failed to delete {f}: {e}")